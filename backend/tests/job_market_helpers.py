"""Synthetic-only helpers for job-market tests. These are not real postings."""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

from app.resume_intelligence.catalog import load_catalog


BACKEND_DIR = Path(__file__).resolve().parents[1]
DATA_DIR = BACKEND_DIR / "data" / "resume_intelligence"
SYNTHETIC_SOURCE_A = "synthetic-india-jobs-a"
SYNTHETIC_SOURCE_B = "synthetic-india-jobs-b"


def synthetic_source(
    source_id: str,
    *,
    status: str = "approved_for_import",
    import_allowed: bool = True,
    geographic_scope: str = "India",
) -> dict[str, Any]:
    return {
        "source_id": source_id,
        "content_kind": "job_postings",
        "job_posting_import_allowed": import_allowed,
        "name": f"Synthetic fixture source {source_id}",
        "official_url": "https://example.invalid/synthetic-job-fixture",
        "format": "Synthetic JSON fixture",
        "acquisition_method": "Generated by tests; never treated as market evidence",
        "version": "synthetic-1.0.0",
        "geographic_scope": geographic_scope,
        "license": {
            "name": "Synthetic test data",
            "url": None,
            "redistribution": "allowed",
            "commercial_use": "allowed",
            "attribution": "Synthetic fixture created only for automated tests.",
        },
        "permitted_use": "Automated tests only.",
        "retention_scope": "Temporary test directory only.",
        "status": status,
        "limitations": [
            "Synthetic fixture; not a real employer, posting, or market statistic."
        ],
        "verified_on": "2026-10-21",
        "verification_note": "Synthetic test fixture.",
    }


def catalog_with_synthetic_sources(
    temp_dir: Path,
    *,
    source_a_kwargs: dict[str, Any] | None = None,
):
    target = temp_dir / "resume_intelligence"
    shutil.copytree(DATA_DIR, target)
    source_path = target / "sources.v1.json"
    document = json.loads(source_path.read_text(encoding="utf-8"))
    document["sources"].extend(
        [
            synthetic_source(
                SYNTHETIC_SOURCE_A, **(source_a_kwargs or {})
            ),
            synthetic_source(SYNTHETIC_SOURCE_B),
        ]
    )
    source_path.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
    return load_catalog(target)


def synthetic_posting(**overrides: Any) -> dict[str, Any]:
    posting = {
        "source_id": SYNTHETIC_SOURCE_A,
        "source_posting_id": "SYN-A-0001",
        "source_reference_url": "https://example.invalid/synthetic/jobs/SYN-A-0001",
        "title": "Software Engineer",
        "employer_name": "Synthetic Employer 1",
        "location": "Bengaluru, Karnataka, India",
        "required_skills": ["Python", "SQL"],
        "preferred_skills": ["Docker"],
        "description": "Synthetic fixture description; not a real job posting.",
        "experience_min_years": 0,
        "experience_max_years": 2,
        "education": "B.Tech",
        "employment_type": "full_time",
        "posted_at": "2026-09-01",
        "collected_at": "2026-10-01",
    }
    posting.update(overrides)
    return posting


def numbered_records(
    postings: list[dict[str, Any]],
) -> list[tuple[int, dict[str, Any]]]:
    return [(index, posting) for index, posting in enumerate(postings, start=1)]
